"""Procedural OBJ helpers for the PyBullet bedroom scene.

PyBullet's built-in GEOM_PLANE has no visual on this build, and textures with
alpha are rendered with a black background, so all textured cards are real
triangle meshes.  The generated meshes are tiny and are written under
``assets/meshes``.
"""
from __future__ import annotations

import math
import os

import numpy as np
import pybullet as p

ROOT = os.path.dirname(os.path.abspath(__file__))
MESH_DIR = os.path.join(ROOT, "assets", "meshes")


def _ensure_dir():
    os.makedirs(MESH_DIR, exist_ok=True)


def _write_obj(name, verts, faces, uvs=None, normals=None):
    _ensure_dir()
    path = os.path.join(MESH_DIR, name + ".obj")
    lines = ["# generated by meshgen.py"]
    for v in verts:
        lines.append("v %.6f %.6f %.6f" % tuple(v))
    if uvs:
        for uv in uvs:
            lines.append("vt %.6f %.6f" % (uv[0], uv[1]))
    if normals:
        for n in normals:
            lines.append("vn %.6f %.6f %.6f" % tuple(n))
    for face in faces:
        parts = []
        for idx in face:
            if uvs and normals:
                parts.append("%d/%d/%d" % (idx + 1, idx + 1, idx + 1))
            elif uvs:
                parts.append("%d/%d" % (idx + 1, idx + 1))
            elif normals:
                parts.append("%d//%d" % (idx + 1, idx + 1))
            else:
                parts.append(str(idx + 1))
        lines.append("f " + " ".join(parts))
    with open(path, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    return path


def quad_mesh(name, width, height, uv_rect=(0.0, 0.0, 1.0, 1.0)):
    """A single quad in the XY plane, normal +Z."""
    w, h = width / 2.0, height / 2.0
    u0, v0, u1, v1 = uv_rect
    verts = [(-w, -h, 0.0), (w, -h, 0.0), (w, h, 0.0), (-w, h, 0.0)]
    uvs = [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]
    normals = [(0.0, 0.0, 1.0)] * 4
    faces = [(0, 1, 2), (0, 2, 3)]
    return _write_obj(name, verts, faces, uvs, normals)


def rounded_rect_panel(name, width, height, radius, thickness=0.004,
                       segments=10, uv_rect=(0.0, 0.0, 1.0, 1.0)):
    """Rounded rectangle prism in the XY plane, front face towards +Z."""
    r = min(radius, width * 0.5, height * 0.5)
    w2, h2 = width / 2.0, height / 2.0
    corners = [
        (w2 - r, -h2 + r, -math.pi / 2.0, 0.0),
        (w2 - r, h2 - r, 0.0, math.pi / 2.0),
        (-w2 + r, h2 - r, math.pi / 2.0, math.pi),
        (-w2 + r, -h2 + r, math.pi, 1.5 * math.pi),
    ]
    outline = []
    for cx, cy, a0, a1 in corners:
        for i in range(segments + 1):
            a = a0 + (a1 - a0) * i / segments
            outline.append((cx + r * math.cos(a), cy + r * math.sin(a)))

    # Remove duplicated points at the seams.
    clean = []
    for x, y in outline:
        if not clean or (abs(x - clean[-1][0]) + abs(y - clean[-1][1])) > 1e-7:
            clean.append((x, y))
    if (abs(clean[0][0] - clean[-1][0]) + abs(clean[0][1] - clean[-1][1])) < 1e-7:
        clean.pop()
    outline = clean

    u0, v0, u1, v1 = uv_rect
    verts = []
    uvs = []
    normals = []
    for z, nz in ((thickness / 2.0, 1.0), (-thickness / 2.0, -1.0)):
        for x, y in outline:
            verts.append((x, y, z))
            uvs.append((u0 + (x / w2 + 1.0) * 0.5 * (u1 - u0),
                        v0 + (y / h2 + 1.0) * 0.5 * (v1 - v0)))
            normals.append((0.0, 0.0, nz))

    n = len(outline)
    # center points for the front and back fans
    front_center = len(verts)
    verts.append((0.0, 0.0, thickness / 2.0))
    uvs.append(((u0 + u1) / 2.0, (v0 + v1) / 2.0))
    normals.append((0.0, 0.0, 1.0))
    back_center = len(verts)
    verts.append((0.0, 0.0, -thickness / 2.0))
    uvs.append(((u0 + u1) / 2.0, (v0 + v1) / 2.0))
    normals.append((0.0, 0.0, -1.0))

    faces = []
    for i in range(n):
        j = (i + 1) % n
        faces.append((front_center, i, j))
        faces.append((back_center, n + j, n + i))
        faces.append((i, n + i, n + j))
        faces.append((i, n + j, j))

    return _write_obj(name, verts, faces, uvs, normals)


def mesh_visual(path, scale=(1.0, 1.0, 1.0), rgba=(1.0, 1.0, 1.0, 1.0),
                flags=0):
    return p.createVisualShape(p.GEOM_MESH, fileName=path,
                               meshScale=list(scale), rgbaColor=list(rgba),
                               flags=flags)


def uv_sphere_mesh(name, rings=24, segments=36):
    """Unit UV sphere with poles on +/-Z, texture u around, v bottom-to-top."""
    verts, uvs, normals = [], [], []
    for i in range(rings + 1):
        v = i / rings
        theta = math.pi * v  # 0 at -Z pole, pi at +Z pole
        z = -math.cos(theta)
        r = math.sin(theta)
        for j in range(segments + 1):
            u = j / segments
            a = 2.0 * math.pi * u
            x = r * math.cos(a)
            y = r * math.sin(a)
            verts.append((x, y, z))
            uvs.append((u, v))
            normals.append((x, y, z))
    faces = []
    for i in range(rings):
        for j in range(segments):
            a = i * (segments + 1) + j
            b = a + 1
            c = a + (segments + 1)
            d = c + 1
            faces.append((a, b, c))
            faces.append((b, d, c))
    return _write_obj(name, verts, faces, uvs, normals)


def ellipsoid_patch_mesh(name, rx, ry, rz, az_half=math.radians(58),
                         el_half=math.radians(52), nu=28, nv=28):
    """Curved, roughly oval patch on the +Z front of an ellipsoid.

    The patch is rectangular in angle space, which gives a soft oval-ish
    silhouette on the curved surface.  Its edge is hidden by hair/lighting.
    """
    verts, uvs, normals = [], [], []
    for iv in range(nv + 1):
        v = iv / nv
        theta = -el_half + 2.0 * el_half * v
        for iu in range(nu + 1):
            u = iu / nu
            phi = -az_half + 2.0 * az_half * u
            x = rx * math.sin(phi) * math.cos(theta)
            y = ry * math.sin(theta)
            z = rz * math.cos(phi) * math.cos(theta)
            verts.append((x, y, z))
            uvs.append((u, v))
            nx = rx * math.sin(phi) * math.cos(theta)
            ny = ry * math.sin(theta)
            nz = rz * math.cos(phi) * math.cos(theta)
            ln = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
            normals.append((nx / ln, ny / ln, nz / ln))
    faces = []
    for iv in range(nv):
        for iu in range(nu):
            a = iv * (nu + 1) + iu
            b = a + 1
            c = a + (nu + 1)
            d = c + 1
            faces.append((a, b, c))
            faces.append((b, d, c))
    return _write_obj(name, verts, faces, uvs, normals)


def rounded_box_mesh(name, width, depth, height, corner_radius=0.02,
                     segments=8):
    """A box with rounded vertical corners (built like a rounded panel
    standing up, with the rounded profile in the XY plane).  The panel is
    made horizontal and then extruded along Z; for typical use, rotate it.
    """
    path = rounded_rect_panel(name, width, depth, corner_radius,
                              thickness=height, segments=segments)
    return path


def triangle_prism_mesh(name, width, height, thickness=0.002):
    """A downward-pointing triangular speech-bubble tail in the XY plane."""
    w, h, t = width * 0.5, height, thickness * 0.5
    verts = [
        (-w, 0.0, t), (w, 0.0, t), (0.0, -h, t),
        (-w, 0.0, -t), (w, 0.0, -t), (0.0, -h, -t),
    ]
    uvs = [(0.0, 1.0), (1.0, 1.0), (0.5, 0.0)] * 2
    normals = [(0.0, 0.0, 1.0)] * 3 + [(0.0, 0.0, -1.0)] * 3
    faces = [
        (0, 2, 1), (3, 4, 5),
        (0, 3, 4), (0, 4, 1),
        (1, 4, 5), (1, 5, 2),
        (2, 5, 3), (2, 3, 0),
    ]
    return _write_obj(name, verts, faces, uvs, normals)


def quilt_mesh(name, width, depth, thickness=0.01, nu=42, nv=26,
               amplitude=1.0, seed=0):
    """A softly rumpled fabric surface for a duvet / folded throw.

    The surface is a height-field grid with smooth vertex normals and a thin
    extruded edge.  It reads much more like cloth than a flat box.
    """
    rng = np.random.default_rng(seed + 100)
    ph1, ph2 = rng.uniform(0, 2 * np.pi, size=2)
    heights = np.zeros((nv + 1, nu + 1), dtype=float)
    for iv in range(nv + 1):
        v = iv / nv
        for iu in range(nu + 1):
            u = iu / nu
            x = (u - 0.5) * width
            y = (v - 0.5) * depth
            h = (0.010 * math.sin(2 * math.pi * u * 1.6 + ph1)
                 + 0.007 * math.cos(2 * math.pi * v * 2.4 + ph2)
                 + 0.004 * math.sin(2 * math.pi * (u * 3.1 + v * 1.7) + ph1 * 0.5))
            # edges fall away like fabric tucked over a mattress
            edge = min(u, 1 - u, v, 1 - v)
            h -= 0.040 * max(0.0, 0.06 - edge) / 0.06
            heights[iv, iu] = h * amplitude
    verts = []
    uvs = []
    for iv in range(nv + 1):
        v = iv / nv
        for iu in range(nu + 1):
            u = iu / nu
            verts.append(((u - 0.5) * width, (v - 0.5) * depth,
                          heights[iv, iu]))
            uvs.append((u, v))
    # smooth normals from finite differences
    normals = []
    for iv in range(nv + 1):
        for iu in range(nu + 1):
            iu0 = max(0, iu - 1)
            iu1 = min(nu, iu + 1)
            iv0 = max(0, iv - 1)
            iv1 = min(nv, iv + 1)
            dx = ((iu1 - iu0) / nu) * width
            dy = ((iv1 - iv0) / nv) * depth
            dzdx = (heights[iv, iu1] - heights[iv, iu0]) / max(dx, 1e-8)
            dzdy = (heights[iv1, iu] - heights[iv0, iu]) / max(dy, 1e-8)
            nx, ny, nz = -dzdx, -dzdy, 1.0
            ln = math.sqrt(nx * nx + ny * ny + nz * nz)
            normals.append((nx / ln, ny / ln, nz / ln))
    faces = []
    for iv in range(nv):
        for iu in range(nu):
            a = iv * (nu + 1) + iu
            b = a + 1
            c = a + (nu + 1)
            d = c + 1
            faces.append((a, b, c))
            faces.append((b, d, c))
    return _write_obj(name, verts, faces, uvs, normals)


def make_card(name, width, height, texture_path=None):
    """Create a double-sided-ish textured card body at the origin."""
    path = quad_mesh(name, width, height)
    vis = p.createVisualShape(p.GEOM_MESH, fileName=path, meshScale=[1, 1, 1],
                              rgbaColor=[1, 1, 1, 1],
                              flags=p.VISUAL_SHAPE_DOUBLE_SIDED)
    body = p.createMultiBody(0, -1, vis)
    if texture_path:
        tex = p.loadTexture(texture_path)
        p.changeVisualShape(body, -1, textureUniqueId=tex)
    return body
